"""
Who is asking, what they may see, and what the product becomes for them.

Three personas were agreed on the 15 Sep call, and they are not three filters on
one dashboard — they change the ROW SET, the pages, the measures and the verbs:

  ae         an Account Executive working their own book. Scoped to the deals
             they own. Asks "what do I do in the next two hours".
  manager    the middle layer Mandeep asked for — "someone who will be looking
             at the patterns of these sales... if anomalies are happening for
             person A more often than other people, or if person B is able to
             upsell more". Scoped to a pod of reps. Asks "who do I coach".
  executive  entity leadership, who also use this to tell the story upward.
             Unscoped. Asks "where do I move money and attention".

**Row-level security is applied before any aggregation**, in `measures.slice_frame`,
and never in the UI. Filtering after aggregation would leak the denominator: an
AE would see their own numerator over an entity total and every percentage on the
page would be quietly wrong.

**The pod roster is derived, and the product says so.** There is no manager or
team column anywhere in the SFDC extract. Inventing one silently would be the
kind of thing that gets noticed in the room, so the roster is generated by a
stated rule — a snake draft of the 70 reps by owned GP into 6 pods, which gives
every pod a comparable mix of large and small books so benchmarking between reps
is legitimate — and the rule is printed in the scope strip.
"""

