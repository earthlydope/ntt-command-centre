@dataclass(frozen=True)
class Principal:
    """A resolved caller: persona plus the identity that narrows their rows."""

    persona: Persona
    identity: str
    identity_label: str
    #: column -> allowed values. Applied with AND, before aggregation.
    predicate: dict[str, tuple[str, ...]] = field(default_factory=dict)

    @property
    def key(self) -> str:
        return self.persona.key

    @property
    def predicate_sql(self) -> str:
        """The same predicate as it would read against the warehouse."""
        if not self.predicate:
            # "1=1" is what an unrestricted predicate compiles to, but it reads
            # as a placeholder rather than as a statement. The scope strip is
            # there to tell a person what they can see.
            return "Everything"
        parts = []
        for col, vals in sorted(self.predicate.items()):
            if len(vals) == 1:
                parts.append(f"{col} = '{vals[0]}'")
            else:
                shown = ", ".join(f"'{v}'" for v in vals[:3])
                more = f", … +{len(vals) - 3}" if len(vals) > 3 else ""
                parts.append(f"{col} IN ({shown}{more})")
        return " AND ".join(parts)

    def apply(self, df: pd.DataFrame) -> pd.DataFrame:
        """Narrow the frame. Called before aggregation, never after."""
        for col, vals in self.predicate.items():
            if col not in df.columns:
                raise KeyError(
                    f"RLS predicate names column '{col}', which is not in this frame. "
                    "Refusing to return unfiltered rows."
                )
            df = df[df[col].isin(vals)]
        return df

    def may_see(self, measure: str) -> bool:
        return measure not in self.persona.deny_measures


