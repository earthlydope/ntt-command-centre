def default_identity(persona_key: str) -> str:
    """
    The identity a cold load lands on.

    For the AE this must never be one of the reps with no open deals — a page
    of six empty cards is a bad first impression of a product whose whole claim
    is that it finds things. The busiest book is chosen instead.
    """
    if persona_key == "ae":
        r = roster().sort_values(["open_opportunities", "gp"], ascending=False)
        return str(r.iloc[0]["owner"])
    if persona_key == "manager":
        p = pods().sort_values("open_opportunities", ascending=False)
        return str(p.iloc[0]["pod_id"])
    return "north-america"


def resolve(persona: str | None = None, identity: str | None = None,
            upn: str | None = None) -> Principal:
    """
    Resolve the caller.

    In production the UPN arrives inside an Entra token and `persona`/`identity`
    do not exist. The demo drives them explicitly, which is the same switch made
    visible rather than a way around it. An unknown value falls back to the
    executive's read-only entity scope rather than to "everything a rep owns",
    which is the correct direction to fail.
    """
    key = persona if persona in PERSONAS else DEFAULT_PERSONA
    if upn and not persona:
        hit = roster().loc[roster()["owner"].str.lower() == upn.split("@")[0]
                           .replace(".", " ").lower()]
        if len(hit):
            key, identity = "ae", str(hit.iloc[0]["owner"])

    p = PERSONAS[key]
    ident = identity or default_identity(key)

    if key == "ae":
        known = set(roster()["owner"])
        if ident not in known:
            ident = default_identity("ae")
        return Principal(p, ident, ident, {"owner": (ident,)})

    if key == "manager":
        members = _pod_members()
        if ident not in members:
            ident = default_identity("manager")
        pod_row = pods().loc[pods()["pod_id"] == ident].iloc[0]
        # "Pod A · Dana Whitfield · 11 reps" states three things in a slot that
        # needs one. The manager's name IS the team, the way people refer to it.
        label = f"{pod_row['manager_name']}'s team"
        return Principal(p, ident, label, {"owner": members[ident]})

    return Principal(p, "north-america", "North America", {})


def describe(principal: Principal) -> dict:
    """The persona block of /api/meta, including the switcher's contents."""
    r = roster()
    return {
        "active": {
            "persona": principal.key,
            "label": principal.persona.label,
            "role": principal.persona.role,
            "jtbd": principal.persona.jtbd,
            "identity": principal.identity,
            "identityLabel": principal.identity_label,
            "predicate": principal.predicate_sql,
            "home": principal.persona.home,
            "pages": list(principal.persona.pages),
            "denyMeasures": list(principal.persona.deny_measures),
            "accent": principal.persona.accent,
        },
        "personas": [
            {
                "key": p.key, "label": p.label, "role": p.role, "jtbd": p.jtbd,
                "home": p.home, "pages": list(p.pages), "accent": p.accent,
                "scopeColumn": p.scope_column,
            }
            for p in PERSONAS.values()
        ],
        "identities": {
            "ae": [
                {"id": row.owner, "label": row.owner,
                 "openDeals": int(row.open_opportunities),
                 "opportunities": int(row.opportunities), "gp": float(row.gp),
                 "pod": row.pod_id}
                for row in r.sort_values("open_opportunities", ascending=False)
                .itertuples(index=False)
            ],
            "manager": [
                {"id": row.pod_id, "label": f"{row.pod_name} · {row.manager_name}",
                 "reps": int(row.reps), "openDeals": int(row.open_opportunities),
                 "gp": float(row.gp)}
                for row in pods().itertuples(index=False)
            ],
            "executive": [{"id": "north-america", "label": "North America", "reps": int(len(r))}],
        },
        "rosterRule": ROSTER_RULE,
    }


def reset_caches() -> None:
    for fn in (roster, pods, _pod_members):
        fn.cache_clear()
