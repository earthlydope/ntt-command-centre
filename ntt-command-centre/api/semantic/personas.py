ROSTER_RULE = (
    "Pods are derived, not read from SFDC — the extract carries no manager or team "
    "column. The 70 reps are ordered by owned ACV GP and snake-drafted into 6 pods, "
    "so every pod holds a comparable mix of large and small books and rep-to-rep "
    "benchmarking within a pod is legitimate. Assignment by LOB, country or industry "
    "was rejected as degenerate: every rep's dominant LOB is Networking, most reps "
    "sell into both countries, and reps average seven industries each."
)


@functools.lru_cache(maxsize=1)
def roster() -> pd.DataFrame:
    """rep -> pod, plus the book statistics the switcher shows."""
    f = facts()
    by_rep = f.groupby("owner").agg(
        gp=("acv_gp", "sum"),
        revenue=("acv_revenue", "sum"),
        lines=("line_code", "count"),
    )
    opp = f.groupby(["owner", "opportunity_code"]).agg(is_open=("is_open", "first")).reset_index()
    counts = opp.groupby("owner").agg(opportunities=("opportunity_code", "nunique"),
                                      open_opportunities=("is_open", "sum"))
    by_rep = by_rep.join(counts).sort_values("gp", ascending=False).reset_index()

    # Snake draft: 0,1,2,3,4,5,5,4,3,2,1,0,0,1,...
    pods = []
    for i in range(len(by_rep)):
        cycle, pos = divmod(i, POD_COUNT)
        pods.append(pos if cycle % 2 == 0 else POD_COUNT - 1 - pos)
    by_rep["pod_id"] = [f"pod-{chr(ord('A') + p)}" for p in pods]
    by_rep["pod_name"] = by_rep["pod_id"].str.replace("pod-", "Pod ", regex=False)
    by_rep["manager_name"] = by_rep["pod_id"].map(_pod_manager)
    return by_rep


_POD_MANAGERS = {
    "pod-A": "Dana Whitfield", "pod-B": "Marcus Lindqvist", "pod-C": "Priya Raghavan",
    "pod-D": "Tomás Oliveira", "pod-E": "Hannah Brecht", "pod-F": "Kenji Nakamura",
}


def _pod_manager(pod_id: str) -> str:
    return _POD_MANAGERS.get(pod_id, "Unassigned")


@functools.lru_cache(maxsize=1)
def pods() -> pd.DataFrame:
    """Pod-level roll-up for the identity picker and the manager's scope strip."""
    r = roster()
    g = r.groupby(["pod_id", "pod_name", "manager_name"]).agg(
        reps=("owner", "nunique"),
        opportunities=("opportunities", "sum"),
        open_opportunities=("open_opportunities", "sum"),
        gp=("gp", "sum"),
    ).reset_index()
    return g.sort_values("pod_id").reset_index(drop=True)


def rep_pod(rep: str) -> str | None:
    r = roster()
    hit = r.loc[r["owner"] == rep, "pod_id"]
    return str(hit.iloc[0]) if len(hit) else None


@functools.lru_cache(maxsize=1)
def _pod_members() -> dict[str, tuple[str, ...]]:
    r = roster()
    return {pod: tuple(g["owner"]) for pod, g in r.groupby("pod_id")}


