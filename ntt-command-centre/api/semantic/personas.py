@dataclass(frozen=True)
class Persona:
    key: str
    label: str
    role: str
    #: One sentence: the decision this person makes with the product.
    jtbd: str
    #: The column the identity narrows on. None = unscoped.
    scope_column: str | None
    scope_op: str  # "eq" | "in" | "all"
    home: str
    pages: tuple[str, ...]
    #: Measures this persona is not entitled to. Enforced in the API and
    #: mirrored into the LLM system prompt, so the model cannot answer a
    #: question its persona may not ask.
    deny_measures: tuple[str, ...] = ()
    accent: str = "#007BC1"


